    std::string GTranspiler::generate(const Program& program) {
        program_name_ = program.name;
        builder_.clear();
        pending_spills_.clear();
        temp_counter_ = 0;
        indent_ = 0;

        std::vector<const EnumDeclaration*> enums;
        std::vector<const StructDeclaration*> structs_and_components;
        std::vector<const FunctionDeclaration*> functions;
        std::vector<const SystemDeclaration*> systems;

        for (const auto& decl : program.declarations) {
            std::visit(match{
                           [&](const EnumDeclaration& e) { enums.push_back(&e); },
                           [&](const StructDeclaration& s) { structs_and_components.push_back(&s); },
                           [&](const FunctionDeclaration& f) { functions.push_back(&f); },
                           [&](const SystemDeclaration& sys) { systems.push_back(&sys); }
                       }, decl->node);
        }

        emit_preamble();

        for (const auto* enum_decl : enums) {
            emit_enum(*enum_decl);
        }
        if (!enums.empty()) {
            line("");
        }

        auto sorted_structs = topo_sort_structs(structs_and_components);
        for (const auto* struct_decl : sorted_structs) {
            emit_struct_or_component(*struct_decl);
        }
        if (!sorted_structs.empty()) {
            line("");
        }

        for (const auto* fn : functions) {
            emit_function_prototype(*fn);
        }
        if (!functions.empty()) {
            line("");
        }

        for (const auto* sys : systems) {
            emit_system(*sys);
        }

        for (const auto* fn : functions) {
            emit_function(*fn, false);
        }

        emit_engine_registration_helpers(sorted_structs, systems);

        indent_--;
        line("} // namespace script");

        return builder_;
    }

    void GTranspiler::emit_preamble() {
        line("// Automatically generated by GlazeScript. Do not edit manually.");
        line("#pragma once");
        line("");
        line("#include <algorithm>");
        line("#include <cstddef>");
        line("#include <cstdint>");
        line("#include <string>");
        line("#include <vector>");
        line("");
        line("#define GLM_ENABLE_EXPERIMENTAL");
        line("#include <glm/glm.hpp>");
        line("#include <glm/gtc/quaternion.hpp>");
        line("#include <glm/gtx/quaternion.hpp>");
        line("");
        line("#include \"project/scene/Scene.hpp\"");
        line("#include \"project/scene/ecs/ComponentRegistry.hpp\"");
        line("#include \"project/scene/ecs/Components.hpp\"");
        line("#include \"project/scene/ecs/Entity.hpp\"");
        line("#include \"glaze/Runtime.hpp\"");
        line("");
        line("namespace script {");
        indent_++;
        line("using namespace engine;");
        line("");
    }

    void GTranspiler::emit_engine_registration_helpers(const std::vector<const StructDeclaration*>& structs,
                                                       const std::vector<const SystemDeclaration*>& systems) {
        std::string clean_name = program_name_;
        if (clean_name.size() >= 8) {
            std::string suffix = clean_name.substr(clean_name.size() - 8);
            std::ranges::transform(suffix, suffix.begin(), [](unsigned char c) { return static_cast<char>(std::tolower(c)); });
            if (suffix == ".gscript") {
                clean_name.erase(clean_name.size() - 8);
            }
        }
        std::ranges::transform(clean_name, clean_name.begin(), [](unsigned char c) { return static_cast<char>(std::tolower(c)); });

        line(std::format("inline void register_components_{}() {{", clean_name));
        indent_++;
        for (const auto* s : structs) {
            if (s->is_component) {
                line(std::format("engine::ComponentRegistry::register_type<{}>();", safe_name(s->name)));
            }
        }
        indent_--;
        line("}");
        line("");
        line(std::format("inline void register_systems_{}(engine::Scene& scene) {{", clean_name));
        indent_++;
        line(std::format("register_components_{}();", clean_name));
        for (const auto* sys : systems) {
            line(std::format("scene.add_system<{}>();", safe_name(sys->name)));
        }
        indent_--;
        line("}");
    }

    // TOPOLOGICAL SORT FOR STRUCTS & COMPONENTS

    std::vector<const StructDeclaration*> GTranspiler::topo_sort_structs(const std::vector<const StructDeclaration*>& decls) {
        std::unordered_map<std::string, const StructDeclaration*> by_name;
        std::vector<std::string> insertion_order;
        for (const auto* d : decls) {
            by_name[d->name] = d;
            insertion_order.push_back(d->name);
        }

        std::unordered_map<std::string, std::unordered_set<std::string>> deps;
        for (const auto* d : decls) {
            std::unordered_set<std::string> field_deps;
            for (const auto& f : d->fields) {
                collect_type_deps(f.type, by_name, field_deps);
            }
            deps[d->name] = std::move(field_deps);
        }

        std::vector<const StructDeclaration*> ordered;
        std::deque<std::string> ready;
        for (const auto& name : insertion_order) {
            if (deps[name].empty()) {
                ready.push_back(name);
            }
        }

        while (!ready.empty()) {
            std::string current = ready.front();
            ready.pop_front();
            ordered.push_back(by_name[current]);
            for (const auto& name : insertion_order) {
                auto& d_set = deps[name];
                if (d_set.erase(current) && d_set.empty()) {
                    ready.push_back(name);
                }
            }
        }

        if (ordered.size() != decls.size()) {
            throw GlazeCompilerError("semantic error: recursive struct/component value dependency detected");
        }
        return ordered;
    }

    void GTranspiler::collect_type_deps(const TypePtr& type,
                                        const std::unordered_map<std::string, const StructDeclaration*>& known_structs,
                                        std::unordered_set<std::string>& out) const {
        if (!type) return;
        if (type->is<NamedType>()) {
            const auto& name = type->as<NamedType>().name;
            if (known_structs.contains(name)) {
                out.insert(name);
            }
        }
        else if (type->is<ListType>()) {
            collect_type_deps(type->as<ListType>().element_type, known_structs, out);
        }
    }

    // DECLARATIONS

    void GTranspiler::emit_enum(const EnumDeclaration& enum_decl) {
        line(std::format("enum class {} {{", safe_name(enum_decl.name)));
        indent_++;
        for (size_t i = 0; i < enum_decl.members.size(); ++i) {
            const auto& member = enum_decl.members[i];
            std::string suffix = (i + 1 < enum_decl.members.size()) ? "," : "";
            if (member.value.has_value()) {
                line(std::format("{} = {}{}", safe_name(member.name), *member.value, suffix));
            }
            else {
                line(std::format("{}{}", safe_name(member.name), suffix));
            }
        }
        indent_--;
        line("};");
    }

    void GTranspiler::emit_struct_or_component(const StructDeclaration& decl) {
        line(std::format("struct {} {{", safe_name(decl.name)));
        indent_++;
        for (const auto& field : decl.fields) {
            std::string field_decl = std::format("{} {}", cpp_type(field.type), safe_name(field.name));
            if (field.initializer) {
                field_decl += " = " + emit_expr(field.initializer) + ";";
            }
            else {
                field_decl += "{};";
            }
            line(field_decl);
        }
        indent_--;
        line("};");
    }

    void GTranspiler::emit_system(const SystemDeclaration& sys) {
        line(std::format("struct {} {{", safe_name(sys.name)));
        indent_++;

        if (sys.on_update.has_value()) {
            line(std::format("static void on_update(engine::Scene& glz$scene, float {}) {{",
                             safe_name(sys.on_update->delta_time_param)));
            indent_++;
            builder_ += emit_statements(sys.on_update->body.statements);
            indent_--;
            line("}");
            line("");
        }

        if (sys.on_event.has_value()) {
            line(std::format("static void on_event(engine::Scene& glz$scene, engine::Event& {}) {{",
                             safe_name(sys.on_event->event_param)));
            indent_++;
            builder_ += emit_statements(sys.on_event->body.statements);
            indent_--;
            line("}");
            line("");
        }

        for (const auto& fn : sys.functions) {
            emit_function(fn, true);
        }

        indent_--;
        line("};");
        line("");
    }

    void GTranspiler::emit_function_prototype(const FunctionDeclaration& fn) {
        line(std::format("static {} {}({});",
                         cpp_type(fn.return_type),
                         safe_name(fn.name),
                         format_param_list(fn.parameters)));
    }

    void GTranspiler::emit_function(const FunctionDeclaration& fn, bool inside_system) {
        line(std::format("static {} {}({}) {{",
                         cpp_type(fn.return_type),
                         safe_name(fn.name),
                         format_param_list(fn.parameters)));
        indent_++;
        builder_ += emit_statements(fn.body.statements);
        indent_--;
        line("}");
        if (!inside_system) {
            line("");
        }
    }

    std::string GTranspiler::format_param_list(const std::vector<Parameter>& params) {
        std::string result;
        for (size_t i = 0; i < params.size(); ++i) {
            if (i > 0) result += ", ";
            result += std::format("{} {}", cpp_param_type(params[i].type), safe_name(params[i].name));
        }
        return result;
    }

    // STATEMENTS

    std::string GTranspiler::emit_statements(const std::vector<StatementPtr>& statements) {
        std::string sb;
        for (const auto& stmt : statements) {
            sb += emit_statement(stmt);
        }
        return sb;
    }

    std::string GTranspiler::emit_statement(const StatementPtr& stmt) {
        return emit_with_spills([&]() {
            return indent() + emit_statement_inner(stmt) + "\n";
        });
    }

    std::string GTranspiler::emit_statement_inner(const StatementPtr& stmt) {
        if (!stmt) return "{}";
        return std::visit(match{
                              [&](const Block& block) { return emit_braced(block); },
                              [&](const IfStatement& if_stmt) {
                                  std::string sb = std::format("if ({}) {}", emit_expr(if_stmt.condition), emit_braced(if_stmt.then_branch));
                                  if (if_stmt.else_branch) {
                                      if (if_stmt.else_branch->is<IfStatement>()) {
                                          sb += " else " + emit_statement_inner(if_stmt.else_branch);
                                      }
                                      else if (if_stmt.else_branch->is<Block>()) {
                                          sb += " else " + emit_braced(if_stmt.else_branch->as<Block>());
                                      }
                                  }
                                  return sb;
                              },
                              [&](const SwitchStatement& switch_stmt) { return emit_switch(switch_stmt); },
                              [&](const ForCStatement& for_c) {
                                  std::string init = for_c.init ? emit_for_clause(for_c.init) : "";
                                  std::string cond = for_c.condition ? emit_expr(for_c.condition) : "";
                                  std::string update = for_c.update ? emit_for_clause(for_c.update) : "";
                                  return std::format("for ({}; {}; {}) {}", init, cond, update, emit_braced(for_c.body));
                              },
                              [&](const ForRangeStatement& for_range) {
                                  std::string elem_type = cpp_param_type(for_range.element_type);
                                  return std::format("for ({} {} : {}) {}",
                                                     elem_type,
                                                     safe_name(for_range.var_name),
                                                     emit_expr(for_range.collection),
                                                     emit_braced(for_range.body));
                              },
                              [&](const ForEcsStatement& for_ecs) { return emit_for_ecs(for_ecs); },
                              [&](const WhileStatement& while_stmt) {
                                  return std::format("while ({}) {}", emit_expr(while_stmt.condition), emit_braced(while_stmt.body));
                              },
                              [&](const DoWhileStatement& do_while) {
                                  return std::format("do {} while ({});", emit_braced(do_while.body), emit_expr(do_while.condition));
                              },
                              [&](const SimpleStatementPtr& simple) { return emit_simple_statement(simple); }
                          }, stmt->node);
    }

    std::string GTranspiler::emit_for_ecs(const ForEcsStatement& for_ecs) {
        std::string comp_types;
        for (size_t i = 0; i < for_ecs.components.size(); ++i) {
            if (i > 0) comp_types += ", ";
            comp_types += safe_name(for_ecs.components[i].component_type);
        }

        std::string exclude_arg;
        if (!for_ecs.excluded_components.empty()) {
            std::string excluded;
            for (size_t i = 0; i < for_ecs.excluded_components.size(); ++i) {
                if (i > 0) excluded += ", ";
                excluded += safe_name(for_ecs.excluded_components[i]);
            }
            exclude_arg = "engine::exclude<" + excluded + ">";
        }

        std::string bindings = "glz$entity";
        for (const auto& b : for_ecs.components) {
            bindings += ", " + safe_name(b.var_name);
        }

        std::string sb;
        sb += std::format("for (auto [{}] : glz$scene.view<{}>({}).each()) {{\n",
                          bindings, comp_types, exclude_arg);
        indent_++;
        if (for_ecs.entity_var_name.has_value()) {
            sb += indent() + std::format("engine::Entity {}{{glz$entity, &glz$scene}};\n",
                                         safe_name(*for_ecs.entity_var_name));
        }
        else {
            sb += indent() + "(void)glz$entity;\n";
        }
        sb += emit_statements(for_ecs.body.statements);
        indent_--;
        sb += indent() + "}";
        return sb;
    }

    std::string GTranspiler::emit_switch(const SwitchStatement& switch_stmt) {
        bool can_use_native_switch = true;
        for (const auto& sc : switch_stmt.cases) {
            if (sc.label) {
                if (!sc.label->is<IntLiteral>() && !sc.label->is<CharLiteral>() && !is_enum_member_access(sc.label)) {
                    can_use_native_switch = false;
                    break;
                }
            }
        }

        if (can_use_native_switch) {
            std::string sb = std::format("switch ({}) {{\n", emit_expr(switch_stmt.selector));
            indent_++;
            for (const auto& sc : switch_stmt.cases) {
                if (sc.label) {
                    sb += indent() + std::format("case {}: {{\n", emit_expr(sc.label));
                }
                else {
                    sb += indent() + "default: {\n";
                }
                indent_++;
                if (sc.body && sc.body->is<Block>()) {
                    sb += emit_statements(sc.body->as<Block>().statements);
                }
                else if (sc.body) {
                    sb += emit_statement(sc.body);
                }
                sb += indent() + "break;\n";
                indent_--;
                sb += indent() + "}\n";
            }
            indent_--;
            sb += indent() + "}";
            return sb;
        }

        std::string selector_temp = spill_if_needed(switch_stmt.selector);
        std::vector<std::string> branches;
        const SwitchCase* default_case = nullptr;

        for (const auto& sc : switch_stmt.cases) {
            if (!sc.label) {
                default_case = &sc;
                continue;
            }
            std::string cond = std::format("({} == {})", selector_temp, emit_expr(sc.label));
            branches.push_back(std::format("if {} {}", cond, emit_switch_case_body(sc.body)));
        }

        if (branches.empty()) {
            return default_case ? emit_switch_case_body(default_case->body) : "{}";
        }

        std::string sb = branches.front();
        for (size_t i = 1; i < branches.size(); ++i) {
            sb += " else " + branches[i];
        }
        if (default_case) {
            sb += " else " + emit_switch_case_body(default_case->body);
        }
        return sb;
    }

    std::string GTranspiler::emit_switch_case_body(const StatementPtr& body) {
        if (!body) return "{}";
        if (body->is<Block>()) {
            return emit_braced(body->as<Block>());
        }
        std::string sb = "{\n";
        indent_++;
        sb += emit_statement(body);
        indent_--;
        sb += indent() + "}";
        return sb;
    }

    std::string GTranspiler::emit_for_clause(const SimpleStatementPtr& stmt) {
        if (!stmt) return "";
        return std::visit(match{
                              [&](const VariableDeclaration& var_decl) {
                                  std::string const_prefix = var_decl.is_mutable ? "" : "const ";
                                  std::string base = std::format("{}{} {}", const_prefix, cpp_type(var_decl.type), safe_name(var_decl.name));
                                  return var_decl.initializer ? base + " = " + emit_expr(var_decl.initializer) : base + "{}";
                              },
                              [&](const Assignment& assign) {
                                  return emit_assignment_no_semicolon(assign);
                              },
                              [&](const ExpressionStatement& expr_stmt) {
                                  return emit_expr(expr_stmt.expression);
                              },
                              [&](const auto&) -> std::string {
                                  throw GlazeCompilerError("internal error: invalid for-clause statement");
                              }
                          }, stmt->node);
    }

    std::string GTranspiler::emit_simple_statement(const SimpleStatementPtr& stmt) {
        if (!stmt) return ";";
        return std::visit(match{
                              [&](const VariableDeclaration& var_decl) {
                                  std::string const_prefix = var_decl.is_mutable ? "" : "const ";
                                  std::string base = std::format("{}{} {}", const_prefix, cpp_type(var_decl.type), safe_name(var_decl.name));
                                  return var_decl.initializer ? base + " = " + emit_expr(var_decl.initializer) + ";" : base + "{};";
                              },
                              [&](const Assignment& assign) {
                                  return emit_assignment_no_semicolon(assign) + ";";
                              },
                              [&](const ReturnStatement& ret) {
                                  return ret.value ? std::format("return {};", emit_expr(ret.value)) : "return;";
                              },
                              [&](const BreakStatement&) {
                                  return std::string("break;");
                              },
                              [&](const ContinueStatement&) {
                                  return std::string("continue;");
                              },
                              [&](const ExpressionStatement& expr_stmt) {
                                  return emit_expr(expr_stmt.expression) + ";";
                              }
                          }, stmt->node);
    }

    std::string GTranspiler::emit_assignment_no_semicolon(const Assignment& assign) {
        if (assign.target && assign.target->is<MemberAccess>()) {
            const auto& ma = assign.target->as<MemberAccess>();
            if (is_entity_type(type_of(ma.object))) {
                std::string receiver = emit_expr(ma.object);
                if (ma.member == "active" && assign.op == "=") {
                    return std::format("{}.set_active({})", receiver, emit_expr(assign.value));
                }
                if (ma.member == "name") {
                    return std::format("{}.get_component<engine::LabelComponent>().tag {} {}",
                                       receiver, assign.op, emit_expr(assign.value));
                }
            }
        }
        return std::format("{} {} {}", emit_expr(assign.target), assign.op, emit_expr(assign.value));
    }

    std::string GTranspiler::emit_braced(const Block& block) {
        std::string sb = "{\n";
        indent_++;
        sb += emit_statements(block.statements);
        indent_--;
        sb += indent() + "}";
        return sb;
    }

    // EXPRESSIONS

    std::string GTranspiler::emit_expr(const ExpressionPtr& expr) {
        if (!expr) return "";
        return std::visit(match{
                              [&](const IntLiteral& i) { return std::to_string(i.value); },
                              [&](const FloatLiteral& f) { return format_float(f.value); },
                              [&](const BoolLiteral& b) { return b.value ? std::string("true") : std::string("false"); },
                              [&](const CharLiteral& c) { return format_char(c.value); },
                              [&](const StringLiteral& s) { return std::format("std::string({})", format_string(s.value)); },
                              [&](const Identifier& id) { return safe_name(id.name); },
                              [&](const UnaryOp& u) { return std::format("({}{})", u.op, emit_expr(u.operand)); },
                              [&](const PostfixOp& p) { return std::format("({}{})", emit_expr(p.operand), p.op); },
                              [&](const BinaryOp& b) { return std::format("({} {} {})", emit_expr(b.left), b.op, emit_expr(b.right)); },
                              [&](const IndexAccess& idx) { return std::format("{}[{}]", emit_expr(idx.array), emit_expr(idx.index)); },
                              [&](const MemberAccess& ma) { return emit_member_access(ma, expr.get()); },
                              [&](const FunctionCall& call) { return emit_function_call(call, expr.get()); }
                          }, expr->node);
    }

    std::string GTranspiler::emit_member_access(const MemberAccess& ma, const Expression* expr_raw) {
        auto it = resolved_.find(expr_raw);
        SymbolPtr sym = (it != resolved_.end()) ? it->second : nullptr;
        if (sym && sym->kind == SymbolKind::ENUM_MEMBER) {
            return std::format("{}::{}", safe_name(sym->owner), safe_name(ma.member));
        }

        TypePtr obj_type = type_of(ma.object);
        std::string receiver = emit_expr(ma.object);

        if (obj_type && obj_type->is<ListType>()) {
            if (ma.member == "size") {
                return std::format("static_cast<uint32_t>({}.size())", receiver);
            }
        }

        if (is_entity_type(obj_type)) {
            if (ma.member == "id") return std::format("static_cast<uint32_t>({})", receiver);
            if (ma.member == "name") return std::format("{}.name()", receiver);
            if (ma.member == "active") return std::format("{}.is_active()", receiver);
            return std::format("{}.{}", receiver, safe_name(ma.member));
        }

        return std::format("{}.{}", receiver, safe_name(ma.member));
    }

    std::string GTranspiler::emit_function_call(const FunctionCall& call, const Expression* /*expr_raw*/) {
        // Direct Identifier Call
        if (call.callee && call.callee->is<Identifier>()) {
            const auto& id = call.callee->as<Identifier>();

            if (s_math_types.contains(id.name)) {
                std::string args;
                for (size_t i = 0; i < call.arguments.size(); ++i) {
                    if (i > 0) args += ", ";
                    args += emit_expr(call.arguments[i]);
                }
                return std::format("glm::{}({})", id.name, args);
            }

            auto res_it = resolved_.find(call.callee.get());
            SymbolPtr sym = (res_it != resolved_.end()) ? res_it->second : nullptr;

            if (sym && (sym->kind == SymbolKind::STRUCT || sym->kind == SymbolKind::COMPONENT)) {
                std::string args;
                for (size_t i = 0; i < call.arguments.size(); ++i) {
                    if (i > 0) args += ", ";
                    args += emit_expr(call.arguments[i]);
                }
                return std::format("{}{{{}}}", safe_name(id.name), args);
            }

            if (sym && sym->kind == SymbolKind::FUNCTION) {
                return std::format("{}({})", safe_name(id.name), emit_call_arguments(call.arguments, sym->parameters));
            }

            std::string args;
            for (size_t i = 0; i < call.arguments.size(); ++i) {
                if (i > 0) args += ", ";
                args += emit_expr(call.arguments[i]);
            }
            return std::format("{}({})", safe_name(id.name), args);
        }

        // Member / Intrinsic Call
        if (call.callee && call.callee->is<MemberAccess>()) {
            const auto& ma = call.callee->as<MemberAccess>();
            auto res_it = resolved_.find(call.callee.get());
            SymbolPtr sym = (res_it != resolved_.end()) ? res_it->second : nullptr;

            if (sym && sym->kind == SymbolKind::FUNCTION && !sym->owner.empty()) {
                return std::format("{}::{}({})",
                                   safe_name(sym->owner),
                                   safe_name(ma.member),
                                   emit_call_arguments(call.arguments, sym->parameters));
            }

            TypePtr receiver_type = type_of(ma.object);
            if (is_entity_type(receiver_type)) {
                return emit_entity_intrinsic_call(ma.object, ma.member, call.arguments);
            }
            if (receiver_type && receiver_type->is<ListType>()) {
                return emit_list_intrinsic_call(ma.object, ma.member, call.arguments);
            }
        }

        throw GlazeCompilerError("internal error: unsupported function call target");
    }

    std::string GTranspiler::emit_entity_intrinsic_call(const ExpressionPtr& receiver_expr,
                                                        const std::string& method,
                                                        const std::vector<ExpressionPtr>& args) {
        std::string receiver = emit_expr(receiver_expr);
        std::string comp_name = safe_name(args.front()->as<Identifier>().name);

        if (method == "get") return std::format("{}.get_component<{}>()", receiver, comp_name);
        if (method == "has") return std::format("{}.has_component<{}>()", receiver, comp_name);
        if (method == "remove") return std::format("{}.remove_component<{}>()", receiver, comp_name);
        if (method == "add") {
            std::string ctor_args;
            for (size_t i = 1; i < args.size(); ++i) {
                if (!ctor_args.empty()) ctor_args += ", ";
                ctor_args += emit_expr(args[i]);
            }
            return std::format("{}.add_component<{}>({})", receiver, comp_name, ctor_args);
        }

        throw GlazeCompilerError(std::format("internal error: unknown entity intrinsic '{}'", method));
    }

    std::string GTranspiler::emit_list_intrinsic_call(const ExpressionPtr& receiver_expr,
                                                      const std::string& method,
                                                      const std::vector<ExpressionPtr>& args) {
        std::string receiver = emit_expr(receiver_expr);
        if (method == "add") return std::format("{}.push_back({})", receiver, emit_expr(args.front()));
        if (method == "get") return std::format("{}.at({})", receiver, emit_expr(args.front()));
        if (method == "clear") return std::format("{}.clear()", receiver);
        if (method == "remove_at") return std::format("glaze::runtime::list_remove_at({}, {})", receiver, emit_expr(args.front()));
        if (method == "remove") return std::format("glaze::runtime::list_remove({}, {})", receiver, emit_expr(args.front()));
        if (method == "has") return std::format("glaze::runtime::list_has({}, {})", receiver, emit_expr(args.front()));

        throw GlazeCompilerError(std::format("internal error: unknown list intrinsic '{}'", method));
    }

    std::string GTranspiler::emit_call_arguments(const std::vector<ExpressionPtr>& args,
                                                 const std::vector<Parameter>& params) {
        std::string result;
        for (size_t i = 0; i < args.size(); ++i) {
            if (i > 0) result += ", ";
            bool passed_by_ref = (i < params.size()) && is_passed_by_reference(params[i].type);
            if (passed_by_ref && !is_lvalue(args[i])) {
                result += spill(args[i]);
            }
            else {
                result += emit_expr(args[i]);
            }
        }
        return result;
    }

    // TYPES & REFERENCE SEMANTICS

    std::string GTranspiler::cpp_type(const TypePtr& type) const {
        if (!type) return "void";
        if (type->is<ListType>()) {
            return std::format("std::vector<{}>", cpp_type(type->as<ListType>().element_type));
        }
        if (type->is<NamedType>()) {
            const auto& name = type->as<NamedType>().name;
            if (name == "void") return "void";
            if (name == "bool") return "bool";
            if (name == "uint8") return "uint8_t";
            if (name == "int8") return "int8_t";
            if (name == "uint32") return "uint32_t";
            if (name == "int32") return "int32_t";
            if (name == "uint64") return "uint64_t";
            if (name == "int64") return "int64_t";
            if (name == "float") return "float";
            if (name == "double") return "double";
            if (name == "char") return "char";
            if (name == "string") return "std::string";
            if (name == "entity") return "engine::Entity";
            if (name == "event") return "engine::Event";
            if (name == "vec2" || name == "vec3" || name == "vec4" ||
                name == "mat2" || name == "mat3" || name == "mat4" || name == "quat") {
                return "glm::" + name;
            }
            return safe_name(name);
        }
        return "void";
    }

    std::string GTranspiler::cpp_param_type(const TypePtr& type) const {
        std::string base = cpp_type(type);
        return is_passed_by_reference(type) ? base + "&" : base;
    }

    bool GTranspiler::is_passed_by_reference(const TypePtr& type) const {
        if (!type) return false;
        if (type->is<ListType>()) return true;
        if (type->is<NamedType>()) {
            const auto& name = type->as<NamedType>().name;
            if (s_value_primitives.contains(name)) return false;
            auto sym = symbols_.lookup_global(name);
            return !sym || sym->kind != SymbolKind::ENUM;
        }
        return false;
    }

    TypePtr GTranspiler::type_of(const ExpressionPtr& expr) const {
        if (!expr) return nullptr;
        return type_of(expr.get());
    }

    TypePtr GTranspiler::type_of(const Expression* expr) const {
        if (!expr) return nullptr;
        auto it = expression_types_.find(expr);
        if (it != expression_types_.end()) return it->second;
        auto res_it = resolved_.find(expr);
        if (res_it != resolved_.end() && res_it->second) return res_it->second->type;
        return nullptr;
    }

    bool GTranspiler::is_entity_type(const TypePtr& type) {
        return type && type->is<NamedType>() && type->as<NamedType>().name == "entity";
    }

    bool GTranspiler::is_enum_member_access(const ExpressionPtr& expr) const {
        if (!expr || !expr->is<MemberAccess>()) return false;
        auto it = resolved_.find(expr.get());
        return (it != resolved_.end() && it->second && it->second->kind == SymbolKind::ENUM_MEMBER);
    }

    bool GTranspiler::is_lvalue(const ExpressionPtr& expr) const {
        if (!expr) return false;
        return std::visit(match{
                              [&](const Identifier&) { return true; },
                              [&](const MemberAccess& ma) {
                                  auto res_it = resolved_.find(expr.get());
                                  if (res_it != resolved_.end() && res_it->second && res_it->second->kind == SymbolKind::ENUM_MEMBER) {
                                      return false;
                                  }
                                  TypePtr obj_t = type_of(ma.object);
                                  if (is_entity_type(obj_t) && (ma.member == "id" || ma.member == "active")) {
                                      return false;
                                  }
                                  return is_lvalue(ma.object);
                              },
                              [&](const IndexAccess& ia) {
                                  return is_lvalue(ia.array);
                              },
                              [&](const auto&) {
                                  return false;
                              }
                          }, expr->node);
    }

    std::string GTranspiler::spill_if_needed(const ExpressionPtr& expr) {
        return is_lvalue(expr) ? emit_expr(expr) : spill(expr);
    }

    std::string GTranspiler::spill(const ExpressionPtr& expr) {
        TypePtr type = type_of(expr);
        std::string temp = std::format("glz$tmp{}", temp_counter_++);
        pending_spills_.push_back(std::format("{} {} = {};", cpp_type(type), temp, emit_expr(expr)));
        return temp;
    }

    // FORMATTING HELPERS

    template<typename F>
    std::string GTranspiler::emit_with_spills(F&& body_generator) {
        auto saved = std::move(pending_spills_);
        pending_spills_.clear();
        std::string body_text = body_generator();
        std::string sb;
        for (const auto& spill_line : pending_spills_) {
            sb += indent() + spill_line + "\n";
        }
        sb += body_text;
        pending_spills_ = std::move(saved);
        return sb;
    }

    std::string GTranspiler::safe_name(const std::string& name) {
        if (s_cpp_keywords.contains(name)) {
            return "glz_" + name;
        }
        return name;
    }

    std::string GTranspiler::format_float(double value) {
        std::string text = std::format("{}", value);
        if (text.find('.') == std::string::npos && text.find('e') == std::string::npos && text.find('E') == std::string::npos) {
            text += ".0";
        }
        return text + "f";
    }

    std::string GTranspiler::format_char(char value) {
        switch (value) {
            case '\'' : return "'\\''";
            case '\\' : return "'\\\\'";
            case '\n' : return "'\\n'";
            case '\t' : return "'\\t'";
            case '\r' : return "'\\r'";
            case '\0' : return "'\\0'";
            default : return std::format("'{}'", value);
        }
    }

    std::string GTranspiler::format_string(const std::string& value) {
        std::string sb = "\"";
        for (char c : value) {
            switch (c) {
                case '"' : sb += "\\\"";
                    break;
                case '\\' : sb += "\\\\";
                    break;
                case '\n' : sb += "\\n";
                    break;
                case '\t' : sb += "\\t";
                    break;
                case '\r' : sb += "\\r";
                    break;
                case '\0' : sb += "\\0";
                    break;
                default : sb += c;
                    break;
            }
        }
        sb += '\"';
        return sb;
    }

    std::string GTranspiler::indent() const {
        return std::string(indent_ * 4, ' ');
    }

    void GTranspiler::line(std::string_view text) {
        if (text.empty()) {
            builder_ += '\n';
        }
        else {
            builder_ += indent() + std::string(text) + '\n';
        }
    }
